// Views/RepairGuide/RepairGuideView.swift
import SwiftUI
import RealityKit

struct RepairGuideView: View {
    let guide: RepairGuide

    @State private var currentStepIndex = 0
    @State private var arCoordinator: ARRepairCoordinator?
    @State private var showToolCheck = false
    @Namespace private var transitionNamespace

    private var currentStep: RepairStep? { guide.steps[safe: currentStepIndex] }

    var body: some View {
        GeometryReader { geo in
            VStack(spacing: 0) {
                // ── Top 48% — AR pane ────────────────────────────────────
                ZStack(alignment: .topTrailing) {
                    RepairGuideARView(
                        guide: guide,
                        currentStepIndex: $currentStepIndex
                    )
                    .matchedGeometryEffect(id: "arPane", in: transitionNamespace)

                    // Tool-check FAB
                    if !guide.steps.isEmpty {
                        Button {
                            showToolCheck = true
                        } label: {
                            Label("Check Tools", systemImage: "wrench.and.screwdriver")
                                .font(Theme.caption)
                                .foregroundStyle(Theme.textPrimary)
                                .padding(.horizontal, Theme.spacingM)
                                .padding(.vertical, Theme.spacingXS)
                                .background(.ultraThinMaterial, in: Capsule())
                                .overlay(Capsule().strokeBorder(.white.opacity(0.2), lineWidth: 1))
                        }
                        .buttonStyle(.plain)
                        .padding(Theme.spacingM)
                    }
                }
                .frame(height: geo.size.height * 0.48)

                // ── Divider ──────────────────────────────────────────────
                Rectangle()
                    .fill(Color.white.opacity(0.08))
                    .frame(height: 1)

                // ── Bottom 52% — Scrollable steps ────────────────────────
                stepsPane
                    .frame(maxHeight: .infinity)
            }
        }
        .background(Color(hex: 0x0D0D0F).ignoresSafeArea())
        .navigationTitle(guide.session.title)
        .navigationBarTitleDisplayMode(.inline)
        .sheet(isPresented: $showToolCheck) {
            if let step = currentStep {
                ToolCheckView(
                    requiredTools: step.toolsRequired,
                    transitionNamespace: transitionNamespace
                )
                .presentationDetents([.large])
                .presentationDragIndicator(.visible)
            }
        }
    }

    // MARK: – Steps pane

    private var stepsPane: some View {
        ScrollViewReader { proxy in
            ScrollView(showsIndicators: false) {
                VStack(spacing: Theme.spacingM) {
                    if let step = currentStep {
                        activeStepDetail(step)
                    }
                    Divider().background(Color.white.opacity(0.08))
                    ForEach(guide.steps) { step in
                        stepRow(step)
                            .id(step.id)
                    }
                    // C2PA compliance footer
                    VStack(spacing: Theme.spacingXS) {
                        AIDisclosureBadge(
                            text: "Instructions generated by Fixie AI. Always verify safety protocols manually.",
                            systemImage: "info.circle"
                        )
                    }
                    .padding(.top, Theme.spacingS)

                    Spacer(minLength: Theme.spacingXL)
                }
                .padding(Theme.spacingM)
            }
            .background(.ultraThinMaterial)
            .onChange(of: currentStepIndex) { _, newIdx in
                if let step = guide.steps[safe: newIdx] {
                    withAnimation(.spring()) { proxy.scrollTo(step.id, anchor: .top) }
                }
            }
        }
    }

    // MARK: – Active step detail (expanded)

    private func activeStepDetail(_ step: RepairStep) -> some View {
        VStack(alignment: .leading, spacing: Theme.spacingM) {
            HStack {
                Text("CURRENT STEP")
                    .font(Theme.caption)
                    .foregroundStyle(Theme.textTertiary)
                    .kerning(0.8)
                Spacer()
                Text("\(step.order) / \(guide.steps.count)")
                    .font(Theme.caption)
                    .foregroundStyle(Theme.brandPrimary)
            }

            Text(step.detail)
                .font(Theme.bodyRegular)
                .foregroundStyle(Theme.textPrimary)
                .fixedSize(horizontal: false, vertical: true)

            if !step.toolsRequired.isEmpty {
                Label(step.toolsRequired.joined(separator: "  ·  "),
                      systemImage: "wrench.fill")
                    .font(Theme.caption)
                    .foregroundStyle(Theme.brandPrimary)
            }

            if let warning = step.warningNote {
                HStack(spacing: Theme.spacingS) {
                    Image(systemName: "exclamationmark.triangle.fill")
                        .foregroundStyle(Theme.warningAmber)
                    Text(warning)
                        .font(Theme.caption)
                        .foregroundStyle(Theme.warningAmber)
                }
                .padding(Theme.spacingS)
                .background(Theme.warningAmber.opacity(0.08), in: RoundedRectangle(cornerRadius: Theme.radiusS))
            }
        }
        .padding(Theme.spacingM)
        .background(
            RoundedRectangle(cornerRadius: Theme.radiusM)
                .fill(Theme.brandPrimary.opacity(0.08))
                .strokeBorder(Theme.brandPrimary.opacity(0.3), lineWidth: 1)
        )
    }

    // MARK: – Step row (compact list)

    private func stepRow(_ step: RepairStep) -> some View {
        let isActive  = step.order - 1 == currentStepIndex
        let isDone    = step.order - 1 < currentStepIndex

        return Button { currentStepIndex = step.order - 1 } label: {
            HStack(alignment: .top, spacing: Theme.spacingM) {
                ZStack {
                    Circle()
                        .fill(isActive ? Theme.brandPrimary
                              : isDone  ? Theme.brandSecondary
                              : Color.white.opacity(0.08))
                        .frame(width: 30, height: 30)
                    if isDone {
                        Image(systemName: "checkmark")
                            .font(.system(size: 12, weight: .bold))
                            .foregroundStyle(.black)
                    } else {
                        Text("\(step.order)")
                            .font(Theme.caption)
                            .foregroundStyle(isActive ? .black : Theme.textSecondary)
                    }
                }

                VStack(alignment: .leading, spacing: 2) {
                    Text(step.title)
                        .font(Theme.bodyBold)
                        .foregroundStyle(isActive ? Theme.textPrimary : Theme.textSecondary)
                    if !step.toolsRequired.isEmpty {
                        Text(step.toolsRequired.joined(separator: " · "))
                            .font(Theme.caption)
                            .foregroundStyle(Theme.textTertiary)
                    }
                }
                .frame(maxWidth: .infinity, alignment: .leading)
            }
            .padding(.vertical, Theme.spacingXS)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .animation(.spring(response: 0.3, dampingFraction: 0.8), value: isActive)
    }
}
